-- RAD-Manager tables (FreeRADIUS's own radcheck/radreply/radacct/nas tables come from its package schema).
CREATE TABLE IF NOT EXISTS rm_admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  pass_hash VARCHAR(100) NOT NULL,
  full_name VARCHAR(128) NOT NULL DEFAULT '',
  role VARCHAR(16) NOT NULL DEFAULT 'viewer',
  manager_id INT NULL,
  enabled TINYINT NOT NULL DEFAULT 1,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS rm_sessions (
  token CHAR(64) PRIMARY KEY,
  admin_id INT NOT NULL,
  expires DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS rm_managers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  adv_id VARCHAR(32) NULL UNIQUE,
  username VARCHAR(64) NOT NULL UNIQUE,
  full_name VARCHAR(128) NOT NULL DEFAULT '',
  parent_id INT NULL,
  phone VARCHAR(32) NOT NULL DEFAULT '',
  balance DECIMAL(14,2) NOT NULL DEFAULT 0,
  unlimited TINYINT NOT NULL DEFAULT 0,
  notes TEXT,
  enabled TINYINT NOT NULL DEFAULT 1,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  raw JSON NULL
);
CREATE TABLE IF NOT EXISTS rm_profiles (
  id INT AUTO_INCREMENT PRIMARY KEY,
  adv_id VARCHAR(32) NULL UNIQUE,
  name VARCHAR(64) NOT NULL UNIQUE,
  price DECIMAL(12,2) NOT NULL DEFAULT 0,
  type_prof TINYINT NOT NULL DEFAULT 0,
  down_speed VARCHAR(16) NOT NULL DEFAULT '',
  up_speed VARCHAR(16) NOT NULL DEFAULT '',
  rate_limit VARCHAR(128) NOT NULL DEFAULT '',
  days INT NOT NULL DEFAULT 30,
  quota_mb BIGINT NOT NULL DEFAULT 0,
  pool VARCHAR(64) NOT NULL DEFAULT '',
  simul INT NOT NULL DEFAULT 1,
  notes TEXT,
  enabled TINYINT NOT NULL DEFAULT 1,
  raw JSON NULL
);
CREATE TABLE IF NOT EXISTS rm_subscribers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  adv_id VARCHAR(32) NULL UNIQUE,
  username VARCHAR(64) NOT NULL UNIQUE,
  password VARCHAR(64) NOT NULL DEFAULT '',
  firstname VARCHAR(128) NOT NULL DEFAULT '',
  lastname VARCHAR(128) NOT NULL DEFAULT '',
  mobile VARCHAR(32) NOT NULL DEFAULT '',
  address VARCHAR(255) NOT NULL DEFAULT '',
  notes TEXT,
  profile_id INT NULL,
  manager_id INT NULL,
  expiration DATETIME NULL,
  quota_mb BIGINT NOT NULL DEFAULT 0,
  used_mb BIGINT NOT NULL DEFAULT 0,
  money DECIMAL(12,2) NOT NULL DEFAULT 0,
  mac VARCHAR(255) NOT NULL DEFAULT '',
  framed_ip VARCHAR(45) NOT NULL DEFAULT '',
  simul INT NOT NULL DEFAULT 1,
  enabled TINYINT NOT NULL DEFAULT 1,
  online TINYINT NOT NULL DEFAULT 0,
  source VARCHAR(8) NOT NULL DEFAULT 'local',
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  raw JSON NULL,
  KEY (expiration), KEY (mobile), KEY (manager_id), KEY (profile_id)
);
CREATE TABLE IF NOT EXISTS rm_invoices (
  id INT AUTO_INCREMENT PRIMARY KEY,
  adv_id VARCHAR(32) NULL UNIQUE,
  kind VARCHAR(16) NOT NULL DEFAULT 'subscriber',
  subscriber_id INT NULL,
  manager_id INT NULL,
  profile_id INT NULL,
  operation VARCHAR(32) NOT NULL DEFAULT 'renew',
  amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount DECIMAL(12,2) NOT NULL DEFAULT 0,
  paid TINYINT NOT NULL DEFAULT 1,
  period_from DATETIME NULL,
  period_to DATETIME NULL,
  notes TEXT,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64) NOT NULL DEFAULT '',
  KEY (created), KEY (subscriber_id), KEY (manager_id)
);
CREATE TABLE IF NOT EXISTS rm_cards (
  id INT AUTO_INCREMENT PRIMARY KEY,
  adv_id VARCHAR(32) NULL UNIQUE,
  kind VARCHAR(16) NOT NULL DEFAULT 'recharge',
  series VARCHAR(64) NOT NULL DEFAULT '',
  code VARCHAR(64) NOT NULL UNIQUE,
  profile_id INT NULL,
  price DECIMAL(12,2) NOT NULL DEFAULT 0,
  manager_id INT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'new',
  used_by INT NULL,
  used_at DATETIME NULL,
  expires DATETIME NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  raw JSON NULL,
  KEY (status)
);
CREATE TABLE IF NOT EXISTS rm_balance_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  manager_id INT NOT NULL,
  delta DECIMAL(14,2) NOT NULL,
  balance_after DECIMAL(14,2) NOT NULL,
  reason VARCHAR(255) NOT NULL DEFAULT '',
  ref VARCHAR(64) NOT NULL DEFAULT '',
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS rm_audit (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  admin VARCHAR(64) NOT NULL DEFAULT '',
  action VARCHAR(64) NOT NULL,
  target VARCHAR(128) NOT NULL DEFAULT '',
  details TEXT,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  KEY (ts)
);
CREATE TABLE IF NOT EXISTS rm_tickets (
  id INT AUTO_INCREMENT PRIMARY KEY,
  subscriber_id INT NULL,
  subject VARCHAR(255) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS rm_ticket_replies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ticket_id INT NOT NULL,
  body TEXT NOT NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS rm_settings (
  k VARCHAR(64) PRIMARY KEY,
  v TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS rm_sync_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ts DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  kind VARCHAR(32) NOT NULL,
  ok TINYINT NOT NULL,
  fetched INT NOT NULL DEFAULT 0,
  changed INT NOT NULL DEFAULT 0,
  message TEXT
);
CREATE TABLE IF NOT EXISTS rm_adv_online (
  username VARCHAR(64) PRIMARY KEY,
  nas VARCHAR(64) NOT NULL DEFAULT '',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  mac VARCHAR(64) NOT NULL DEFAULT '',
  since VARCHAR(32) NOT NULL DEFAULT ''
);
-- ADV history kept here before migration (أرشيف ADV): its activity log and every subscriber's past sessions
CREATE TABLE IF NOT EXISTS rm_adv_activity (
  id BIGINT PRIMARY KEY,
  ts VARCHAR(32) NOT NULL DEFAULT '',
  id_user VARCHAR(32) NOT NULL DEFAULT '',
  action VARCHAR(16) NOT NULL DEFAULT '',
  manager VARCHAR(64) NOT NULL DEFAULT '',
  details TEXT,
  raw JSON,
  KEY (id_user), KEY (ts)
);
CREATE TABLE IF NOT EXISTS rm_adv_sessions (
  id BIGINT PRIMARY KEY,
  username VARCHAR(64) NOT NULL DEFAULT '',
  nas VARCHAR(64) NOT NULL DEFAULT '',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  mac VARCHAR(64) NOT NULL DEFAULT '',
  start VARCHAR(32) NOT NULL DEFAULT '',
  stop VARCHAR(32) NOT NULL DEFAULT '',
  session_sec BIGINT NOT NULL DEFAULT 0,
  bytes_in BIGINT NOT NULL DEFAULT 0,
  bytes_out BIGINT NOT NULL DEFAULT 0,
  KEY (username), KEY (start)
);
-- الاستهلاك اليومي: bytes per subscriber per calendar day (filled from the open sessions' counters every 20 s)
CREATE TABLE IF NOT EXISTS rm_daily_usage (
  day DATE NOT NULL,
  username VARCHAR(64) NOT NULL,
  bytes_in BIGINT NOT NULL DEFAULT 0,
  bytes_out BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (day, username), KEY (username)
);
CREATE TABLE IF NOT EXISTS rm_usage_track (
  acct BIGINT PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  bytes_in BIGINT NOT NULL DEFAULT 0,
  bytes_out BIGINT NOT NULL DEFAULT 0,
  seen DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
